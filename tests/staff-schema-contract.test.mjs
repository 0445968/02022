import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
const dir = new URL('../supabase/migrations/', import.meta.url);
const matches = readdirSync(dir).filter((name) => /^\d{14}_ct02b_staff_access\.sql$/.test(name));
assert.equal(matches.length, 1, 'Migration filename must be generated by Supabase CLI');
const sql = readFileSync(new URL(matches[0], dir), 'utf8');
const server = readFileSync(new URL('../lib/permissions/server.ts', import.meta.url), 'utf8');
const tableNames = [
  'staff_memberships','staff_role_presets','staff_role_capabilities','staff_member_roles',
  'staff_capability_overrides','staff_story_assignments','staff_access_audit',
];

test('migration defines RLS for every new public staff table', () => {
  for (const name of tableNames) {
    assert.match(sql, new RegExp('create table public\\.' + name + ' \\('));
    assert.match(sql, new RegExp('alter table public\\.' + name + ' enable row level security;'));
  }
});

test('only scoped SELECT policies exist, not unreviewed user write permissions', () => {
  assert.equal((sql.match(/create policy /gi) || []).length, 6);
  assert.doesNotMatch(sql, /create policy [\s\S]*?for (insert|update|delete) to authenticated/i);
  assert.doesNotMatch(sql, /grant\s+(insert|update|delete|all)\s+on\s+table[\s\S]*?to authenticated/i);
  assert.doesNotMatch(sql, /to anon;/i);
  assert.match(sql, /revoke all on table/);
});

test('audit is immutable through the API and never exposed to ordinary authenticated users', () => {
  assert.match(sql, /grant select, insert on public\.staff_access_audit to service_role;/);
  assert.doesNotMatch(sql, /staff_access_audit\s+for select to authenticated/i);
  assert.doesNotMatch(sql, /grant select on public\.staff_access_audit to authenticated/i);
});

test('new schema does not touch working story data or legacy editorial roles', () => {
  assert.doesNotMatch(sql, /update\s+public\.profiles|alter\s+table\s+public\.(stories|profiles|story_revisions)/i);
  assert.doesNotMatch(sql, /dev_auth_bypass|disable row level security|security definer/i);
  assert.match(sql, /references public\.stories\(id\) on delete restrict/);
});

test('role preset names create no effective capabilities and no automatic legacy membership backfill', () => {
  assert.match(sql, /insert into public\.staff_role_presets/);
  assert.doesNotMatch(sql, /insert into public\.(staff_memberships|staff_role_capabilities|staff_member_roles)/i);
  assert.match(sql, /no_ordinary_security_admin_grant/);
  assert.match(sql, /no_security_admin_override/);
});

test('authenticated staff can only select their own membership and current role rows', () => {
  assert.match(sql, /auth_user_id = \(select auth\.uid\(\)\)/);
  assert.match(sql, /m\.status = 'active'/);
  assert.match(sql, /m\.expires_at > now\(\)/);
  assert.match(sql, /mr\.expires_at > now\(\)/);
});

test('new server resolver fails closed before enablement and uses a verified account', () => {
  assert.match(server, /CT_STAFF_ACCESS_V2_ENABLED !== 'true'/);
  assert.match(server, /client\.auth\.getUser\(\)/);
  assert.match(server, /\.eq\('auth_user_id', user\.id\)/);
  assert.match(server, /return denied;/);
  assert.doesNotMatch(server, /user_metadata|DEV_AUTH_BYPASS|createDataClient\(|SUPABASE_SERVICE_ROLE_KEY/);
});

test('staff story resource scope is loaded by the server, not accepted from client snapshots', () => {
  assert.match(server, /\.from\('staff_story_assignments'\)/);
  assert.match(server, /\.eq\('membership_id', m\.id\)/);
  assert.match(server, /\.eq\('status', 'active'\)/);
  assert.match(server, /resolveEffectivePermission\(/);
});

test('migration enum matches the finite capabilities registry', () => {
  const source = readFileSync(new URL('../lib/permissions/capabilities.ts', import.meta.url), 'utf8');
  const keys = [...source.matchAll(/^\s*'([^']+)'/gm)].map((match) => match[1]);
  const sqlEnum = sql.slice(sql.indexOf('create type public.staff_capability_key'), sql.indexOf('create table public.staff_memberships'));
  for (const key of keys.filter((value) => value.includes('.'))) {
    assert.ok(sqlEnum.includes("'" + key + "'"), 'Missing capability: ' + key);
  }
});
